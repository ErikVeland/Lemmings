#!/usr/bin/env python3
"""Extract and check the shared interface catalogue without opening app windows."""
import argparse
import collections
import json
from pathlib import Path
import plistlib
import re
import subprocess
from validate import validate_source_messages, validate_texts, validate_plurals, read_json

ROOT = Path(__file__).resolve().parents[2]
BUNDLE = ROOT / 'Sources/NxlvKit/Resources/Localization.bundle'
MODULES = ('NxlvKit', 'LemmingsAppCore', 'LemmingsMobileCore', 'LemmingsGameArt', 'LemmingsLocal', 'LemmingsMobileUI', 'LemmingsTVCore', 'LemmingsTVUI')


def extract():
    build = ROOT / '.build/localisation-tools'
    build.mkdir(parents=True, exist_ok=True)
    compiler = Path(subprocess.check_output(['xcrun', '--find', 'swiftc'], text=True).strip())
    host = compiler.parent.parent / 'lib/swift/host'
    binary = build / 'extract'
    source = Path(__file__).with_name('extract.swift')
    if not binary.exists() or source.stat().st_mtime > binary.stat().st_mtime:
        sdk = subprocess.check_output(['xcrun', '--sdk', 'macosx', '--show-sdk-path'], text=True).strip()
        subprocess.run([str(compiler), '-sdk', sdk, '-module-cache-path', str(build / 'ModuleCache'), '-I', str(host), '-L', str(host), '-lSwiftParser', '-lSwiftSyntax', '-Xlinker', '-rpath', '-Xlinker', str(host), str(source), '-o', str(binary)], check=True)
    files = sorted(str(p.relative_to(ROOT)) for module in MODULES for p in (ROOT / 'Sources' / module).rglob('*.swift'))
    data = json.loads(subprocess.check_output([str(binary), *files], cwd=ROOT))
    original = json.loads(Path(__file__).with_name('l2-original-text.json').read_text())
    for key, references in original.items():
        data['messages'] += [{'key': key, 'kind': 'text', 'file': file, 'line': 1} for file in references]
    return data


def quote(value):
    return json.dumps(value, ensure_ascii=False)


def outputs(rows):
    groups = collections.defaultdict(list)
    plurals = {}
    for row in rows:
        if row['kind'] == 'plural':
            entry = {'NSStringLocalizedFormatKey': '%#@count@', 'count': {'NSStringFormatSpecTypeKey': 'NSStringPluralRuleType', 'NSStringFormatValueTypeKey': 'ld', 'one': row['one'], 'other': row['other']}}
            if row['key'] in plurals and plurals[row['key']] != entry:
                raise ValueError('Conflicting plural key: ' + row['key'])
            plurals[row['key']] = entry
        groups[row['key']].append(row)
    lines = ['/* Generated by Tools/Localisation/catalogue.py. English is the source language. */', '']
    catalogue = {}
    for key, group in sorted(groups.items()):
        references = sorted(set(f"{r['file']}:{r['line']}" for r in group))
        catalogue[key] = {'kind': group[0]['kind'], 'references': references}
        if group[0]['kind'] == 'text':
            lines += ['/* ' + '; '.join(references).replace('*/', '* /') + ' */', f'{quote(key)} = {quote(key)};', '']
    return '\n'.join(lines) + '\n', plistlib.dumps(plurals, sort_keys=True), json.dumps(catalogue, ensure_ascii=False, indent=2, sort_keys=True) + '\n'


def validate_translations(english_keys, plural_keys):
    review_file = Path(__file__).with_name('unchanged.json')
    reviews = read_json(review_file) if review_file.exists() else {}
    for locale in sorted(BUNDLE.glob('*.lproj')):
        strings = locale / 'Interface.strings'
        if not strings.exists():
            raise ValueError(f'Missing interface table: {locale.name}')
        # plutil reads Apple's text .strings format, including escapes and comments.
        data = json.loads(subprocess.check_output(['plutil', '-convert', 'json', '-o', '-', str(strings)]))
        language = locale.stem
        errors, missing = validate_texts(english_keys, data, english_keys if language == 'en' else reviews.get(language, {}))
        if errors or missing:
            raise ValueError(f'{locale.name}: {len(missing)} missing texts; ' + '; '.join(errors[:5]))
        for key, value in data.items():
            if key not in english_keys:
                raise ValueError(f'{locale.name}: unknown key {key!r}')
            if not isinstance(value, str) or set(re.findall(r'\{\d+\}', key)) != set(re.findall(r'\{\d+\}', value)):
                raise ValueError(f'{locale.name}: invalid placeholders for {key!r}')
        dictionary = locale / 'Interface.stringsdict'
        if plural_keys and not dictionary.exists():
            raise ValueError(f'Missing plural table: {locale.name}')
        if dictionary.exists():
            entries = plistlib.loads(dictionary.read_bytes())
            errors, missing = validate_plurals(plural_keys, {
                key: {category: text for category, text in value.get('count', {}).items()
                      if category in {'zero', 'one', 'two', 'few', 'many', 'other'}}
                for key, value in entries.items()})
            if errors or missing:
                raise ValueError(f'{locale.name}: {len(missing)} missing plurals; ' + '; '.join(errors[:5]))
            for key, value in plistlib.loads(dictionary.read_bytes()).items():
                if key not in plural_keys or value.get('NSStringLocalizedFormatKey') != '%#@count@':
                    raise ValueError(f'{locale.name}: unknown or malformed plural {key!r}')
                count = value.get('count', {})
                if count.get('NSStringFormatSpecTypeKey') != 'NSStringPluralRuleType' or count.get('NSStringFormatValueTypeKey') != 'ld' or 'other' not in count:
                    raise ValueError(f'{locale.name}: incomplete plural {key!r}')
                for category, text in count.items():
                    if category in {'zero', 'one', 'two', 'few', 'many', 'other'} and (not isinstance(text, str) or re.sub(r'%%|%ld', '', text).find('%') >= 0):
                        raise ValueError(f'{locale.name}: unsupported count format for {key!r}')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if generated source catalogues are stale.')
    parser.add_argument('--audit', action='store_true', help='Report direct UI literals that still need migration.')
    args = parser.parse_args()
    data = extract()
    source_errors = validate_source_messages(data['messages'])
    if source_errors:
        raise SystemExit('\n'.join(source_errors))
    exemptions = json.loads(Path(__file__).with_name('exemptions.json').read_text())
    exempt = {(r['file'], r['source']) for r in exemptions}
    data['uncovered'] = [r for r in data['uncovered'] if (r['file'], r['source']) not in exempt]
    if args.check and data['uncovered']:
        raise SystemExit(f"{len(data['uncovered'])} direct UI literals need localisation. Run with --audit to inspect them.")
    strings, plurals, catalogue = outputs(data['messages'])
    products = {BUNDLE / 'en.lproj/Interface.strings': strings.encode(), BUNDLE / 'en.lproj/Interface.stringsdict': plurals, ROOT / 'Documentation/LocalisationCatalogue.json': catalogue.encode()}
    for path, content in products.items():
        if args.check:
            if not path.exists() or path.read_bytes() != content:
                raise SystemExit(f'Stale localisation catalogue: {path.relative_to(ROOT)}. Run Tools/Localisation/catalogue.py.')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
    validate_translations({r['key'] for r in data['messages'] if r['kind'] == 'text'}, {r['key'] for r in data['messages'] if r['kind'] == 'plural'})
    if args.audit:
        for row in data['uncovered']:
            print(f"{row['file']}:{row['line']}: {row['source']}")
    print(f"{len(data['messages'])} message uses; {len(json.loads(catalogue))} translation keys; {len(data['uncovered'])} direct UI literals to review")


if __name__ == '__main__':
    main()
